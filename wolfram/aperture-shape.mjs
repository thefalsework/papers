// ----- Rieger-Nishimura truncations Z_n -----
// join-irreducibles q1,q2,q3,... : q1,q2 minimal; q3 > q1; q_m covers q_{m-2}, q_{m-3} (m>=4).
// Z_{2m}   = Down(q1..qm)            (m>=3)
// Z_{2m+1} = Down(q1..qm + top point)
function ladder(m) {
  const below = [];
  for (let i = 0; i < m; i++) {
    let b = 1 << i;
    if (i === 2) b |= below[0];
    if (i >= 3) b |= below[i - 2] | below[i - 3];
    below.push(b);
  }
  return below;
}
function zn(nElems) {
  const m = Math.floor(nElems / 2);
  let below = ladder(m);
  if (nElems % 2 === 1) below = [...below, (1 << m) | ((1 << m) - 1)];
  return below;
}
