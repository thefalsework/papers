// Aperture-shape sweep (route 1): what kind of subset of the nucleus lattice is an
// aperture?  Pre-registered question (2026-10-28, before the run): is Ap(k) always
// order-convex in the nucleus lattice, and is it the intersection of two order-convex
// families (observers under which k is not dense; observers under which k is not regular)?
//
// Pre-registered anchors (must reproduce exactly, or the run is void):
//   Div12  nuclei 8,  Ap(2) = {identity}, coAp(2) = 18        (ApertureAnchors.lean, CoApertureClosedForm.lean)
//   Div36  nuclei 16, Ap(6) = 2 with 6 dense ambiently, fix-sets {2,4,6,12,18,36}, {3,6,9,12,18,36}
//   Div24  nuclei 16, Ap(2) = Ap(4) = 3
//   Z_6..Z_14 apertures 1,2,2,4,4,8,8,16,16; co-apertures 18,38,42,86,90,182,186,374,378
//
// RESULT (run 2026-10-28, posets through 7 points, 2450 posets, 54,723 (algebra, kernel) pairs):
//   anchors all reproduced; nucleus generation by subsets cross-checked against brute force
//   on every algebra with <= 12 elements.
//   CONVEXITY FAILS.  12,355 of 31,910 non-empty apertures are not order-convex; first
//   failure at 5 points, inside the paper's own data: Div180 = Down({0<3}+{1<4}+{2}),
//   kernel 6 = {0,1}: S={0,3,4} opens, S u {1} does not (jk becomes world-dense), P opens.
//   Neither ND(k) nor NR(k) is convex either (ND fails on Div12).
//   WHAT HOLDS (criterionFail 0, bottomMismatch 0, fiberNotUp 0 across the whole sweep):
//     with M = min(S):  j_S opens k  iff  M not subset of k  and  some s in S \ k has (down s) n M subset of k;
//     j_S(bot) = P \ up(M);  Ap(k) is an up-set within each fiber { S : min S = M }.
//   The criterion is proved in lean/FalseWorkPapers/Lattice/ApertureCriterion.lean; the
//   write-up is preprints/aperture/aperture-shape-note.md.
//
// Usage: node wolfram/aperture-shape.mjs [maxPoints]   (default 6; 7 takes ~15 s)
// Route 1: shape of apertures in the nucleus lattice, on all small finite Heyting algebras.
//
// Finite Heyting algebra = Down(P) for a finite poset P (Birkhoff). Nuclei on Down(P)
// correspond to subsets S of P:  j_S(U) = { p : for all s in S, s <= p  ->  s in U }.
// (Generation by subsets; every candidate is re-checked against the three nucleus laws,
// and for small algebras the count is cross-checked against brute force over meet-closed
// subsets containing top, as in preprints/aperture/paper.md section 4.)
//
// Questions tested, for every k in H:
//   Q1  is Ap(k) order-convex in the nucleus lattice?
//   Q2  are ND(k) = { j : jk not dense in Fix j } and NR(k) = { j : jk not regular in Fix j }
//       each order-convex?  up-sets?  down-sets?  (orientation: S subset of T means j_T finer)
//   Q3  is Ap(k) a principal up-set (all S containing a core)?  an up-set at all?
//
// Usage: node enum.mjs [maxPoints]      (default 6)

const MAXN = Number(process.argv[2] ?? 6);

// ---------- posets ----------
// A poset on n points is given by below[p] = bitmask of points <= p (including p).
// Natural labeling: q < p implies q < p as integers. Generated by extension: the new
// point n-1 is placed above a down-set D of the (n-1)-point poset.

function downSets(below, n) {
  // all down-sets of P as bitmasks
  const full = (1 << n) - 1;
  const out = [];
  for (let U = 0; U <= full; U++) {
    let ok = true;
    for (let p = 0; p < n && ok; p++) if ((U >> p) & 1) if ((below[p] & ~U) !== 0) ok = false;
    if (ok) out.push(U);
  }
  return out;
}

function* posets(n) {
  if (n === 0) { yield []; return; }
  for (const B of posets(n - 1)) {
    const ds = downSets(B, n - 1);
    for (const D of ds) {
      // new point n-1 is above exactly the points of D (D is a down-set, so transitive)
      yield [...B, D | (1 << (n - 1))];
    }
  }
}

// canonical form for isomorphism dedup (n <= 7: brute force over permutations)
function permutations(n) {
  const out = [];
  const a = [...Array(n).keys()];
  (function rec(i) {
    if (i === n) { out.push([...a]); return; }
    for (let j = i; j < n; j++) { [a[i], a[j]] = [a[j], a[i]]; rec(i + 1); [a[i], a[j]] = [a[j], a[i]]; }
  })(0);
  return out;
}
const PERMS = {};
function invariantClasses(below, n) {
  // iterated refinement: start from (|down|, |up|), refine by multiset of neighbours' labels
  let lab = [];
  for (let p = 0; p < n; p++) {
    let up = 0; for (let q = 0; q < n; q++) if ((below[q] >> p) & 1) up++;
    lab.push(`${popcount(below[p])}:${up}`);
  }
  for (let it = 0; it < 3; it++) {
    const nl = [];
    for (let p = 0; p < n; p++) {
      const dn = [], upl = [];
      for (let q = 0; q < n; q++) { if (q !== p && ((below[p] >> q) & 1)) dn.push(lab[q]); if (q !== p && ((below[q] >> p) & 1)) upl.push(lab[q]); }
      nl.push(`${lab[p]}|${dn.sort().join(',')}|${upl.sort().join(',')}`);
    }
    lab = nl;
  }
  return lab;
}
const popcount = x => { let c = 0; while (x) { x &= x - 1; c++; } return c; };
function canon(below, n) {
  // permutations consistent with invariant classes only
  const lab = invariantClasses(below, n);
  const order = [...Array(n).keys()].sort((a, b) => lab[a] < lab[b] ? -1 : lab[a] > lab[b] ? 1 : 0);
  // group consecutive equal labels; enumerate products of permutations within groups
  const groups = [];
  for (const p of order) { const g = groups[groups.length - 1]; if (g && lab[g[0]] === lab[p]) g.push(p); else groups.push([p]); }
  const perms = [[]];
  let slot = 0;
  const assignments = [];
  (function rec(gi, cur) {
    if (gi === groups.length) { assignments.push([...cur]); return; }
    const g = groups[gi];
    PERMS[g.length] ??= permutations(g.length);
    for (const pi of PERMS[g.length]) { const ext = cur.slice(); for (let i = 0; i < g.length; i++) ext[g[i]] = slot + pi[i]; slot += g.length; rec(gi + 1, ext); slot -= g.length; }
  })(0, new Array(n).fill(0));
  let best = null;
  for (const perm of assignments) {
    // relabel: new point perm[p] for old p
    const nb = new Array(n).fill(0);
    for (let p = 0; p < n; p++) {
      let m = 0;
      for (let q = 0; q < n; q++) if ((below[p] >> q) & 1) m |= 1 << perm[q];
      nb[perm[p]] = m;
    }
    const key = nb.join(',');
    if (best === null || key < best) best = key;
  }
  return best;
}

// ---------- Heyting algebra Down(P) ----------
function algebra(below, n) {
  const H = downSets(below, n);
  const idx = new Map(H.map((U, i) => [U, i]));
  const full = (1 << n) - 1;
  const himp = (U, V) => { // largest down-set W with W & U <= V :  p in W iff (below[p] & U) <= V
    let W = 0;
    for (let p = 0; p < n; p++) if ((below[p] & U & ~V) === 0) W |= 1 << p;
    return W;
  };
  return { n, below, H, idx, full, himp };
}

function nucleusOf(A, S) {
  // j_S(U) = { p : (below[p] & S) subset of U }
  const { n, below, H } = A;
  const j = new Map();
  for (const U of H) {
    let V = 0;
    for (let p = 0; p < n; p++) if ((below[p] & S & ~U) === 0) V |= 1 << p;
    j.set(U, V);
  }
  return j;
}

function isNucleus(A, j) {
  const { H, idx } = A;
  for (const U of H) {
    const jU = j.get(U);
    if (!idx.has(jU)) return false;            // lands in H
    if ((U & ~jU) !== 0) return false;         // inflationary
    if (j.get(jU) !== jU) return false;        // idempotent
  }
  for (const U of H) for (const V of H) {     // meet-preserving
    if (j.get(U & V) !== (j.get(U) & j.get(V))) return false;
  }
  return true;
}

// brute force: meet-closed subsets containing top, induced closure, filtered by the laws
function bruteNuclei(A) {
  const { H, full } = A;
  const m = H.length;
  const top = H.indexOf(full);
  const found = new Set();
  for (let mask = 0; mask < (1 << m); mask++) {
    if (!((mask >> top) & 1)) continue;
    const F = [];
    for (let i = 0; i < m; i++) if ((mask >> i) & 1) F.push(H[i]);
    let closed = true;
    for (const U of F) { for (const V of F) if (!((mask >> A.idx.get(U & V)) & 1)) { closed = false; break; } if (!closed) break; }
    if (!closed) continue;
    const j = new Map();
    for (const U of H) { let best = full; for (const V of F) if ((U & ~V) === 0 && (V & ~best) === 0) best = V; j.set(U, best); }
    if (isNucleus(A, j)) found.add(H.map(U => j.get(U)).join(','));
  }
  return found;
}

// ordinariness of jk inside Fix(j)
function opens(A, j, k) {
  const bot = j.get(0);
  const jk = j.get(k);
  const neg = x => A.himp(x, bot);       // implication is inherited by Fix(j)
  const n1 = neg(jk);
  const notDense = n1 !== bot;
  const notRegular = neg(n1) !== jk;
  return { notDense, notRegular, open: notDense && notRegular, jk };
}

function phantom(A, j, k) {
  const jk = j.get(k);
  let c = 0;
  for (const U of A.H) if ((k & ~U) === 0 && (U & ~jk) === 0) c++;
  return c;
}

// ---------- shape tests on a family F of subsets S (bitmask over 0..2^n-1) ----------
function shape(F, n) {
  const N = 1 << n;
  const inF = new Uint8Array(N); for (const S of F) inF[S] = 1;
  // hasBelow[S] = exists T in F with T subset S ; hasAbove[S] = exists T in F with T superset S
  const hasBelow = Uint8Array.from(inF), hasAbove = Uint8Array.from(inF);
  for (let b = 0; b < n; b++) for (let S = 0; S < N; S++) {
    if ((S >> b) & 1) { if (hasBelow[S ^ (1 << b)]) hasBelow[S] = 1; }
    else { if (hasAbove[S | (1 << b)]) hasAbove[S] = 1; }
  }
  let convex = true, upset = true, downset = true;
  for (let S = 0; S < N; S++) {
    if (!inF[S] && hasBelow[S] && hasAbove[S]) convex = false;
    if (inF[S]) for (let b = 0; b < n; b++) {
      if (!((S >> b) & 1) && !inF[S | (1 << b)]) upset = false;
      if (((S >> b) & 1) && !inF[S ^ (1 << b)]) downset = false;
    }
  }
  // principal up-set: F = all supersets of its unique minimal element
  let minimal = F.filter(S => !F.some(T => T !== S && (T & ~S) === 0));
  const principalUp = upset && minimal.length === 1;
  return { convex, upset, downset, principalUp, minimal, size: F.length };
}

// ---------- conjectured combinatorial criterion ----------
// Fix(j_S) is isomorphic to Down(S) with S as a subposet, and j_S k corresponds to k & S.
// A down-set D of S is dense iff min(S) subset D; regular iff D contains every s in S all of
// whose minimal predecessors (in S) lie in D.  Hence
//   S opens k  iff  (i) some minimal point of S lies outside k, and
//                   (ii) some point s of S outside k has all its S-minimal predecessors inside k.
function minOf(below, n, S) {
  let M = 0;
  for (let p = 0; p < n; p++) if ((S >> p) & 1) if ((below[p] & S) === (1 << p)) M |= 1 << p;
  return M;
}
function criterion(below, n, S, k) {
  const M = minOf(below, n, S);
  const i = (M & ~k) !== 0;
  let ii = false;
  for (let s = 0; s < n && !ii; s++) if (((S >> s) & 1) && !((k >> s) & 1)) if ((below[s] & M & ~k) === 0) ii = true;
  return { open: i && ii, M, notDense: i, notRegular: ii };
}

// ---------- run ----------
function analyse(below, n, opts = {}) {
  const A = algebra(below, n);
  const N = 1 << n;
  const nuclei = [];
  for (let S = 0; S < N; S++) {
    const j = nucleusOf(A, S);
    if (!isNucleus(A, j)) throw new Error(`j_S failed nucleus laws: S=${S} P=${below}`);
    nuclei.push({ S, j });
  }
  if (opts.brute && A.H.length <= 12) {
    const bf = bruteNuclei(A);
    const mine = new Set(nuclei.map(({ j }) => A.H.map(U => j.get(U)).join(',')));
    if (bf.size !== mine.size || [...bf].some(x => !mine.has(x))) throw new Error(`brute-force nucleus mismatch on P=${below}: ${bf.size} vs ${mine.size}`);
  }
  const perK = [];
  for (const k of A.H) {
    const Ap = [], ND = [], NR = [];
    let coAp = 0;
    for (const { S, j } of nuclei) {
      const o = opens(A, j, k);
      if (o.open) Ap.push(S);
      if (o.notDense) ND.push(S);
      if (o.notRegular) NR.push(S);
      coAp += phantom(A, j, k);
    }
    perK.push({ k, Ap, ND, NR, coAp, sAp: shape(Ap, n), sND: shape(ND, n), sNR: shape(NR, n) });
  }
  return { A, nuclei, perK };
}

const fmtSet = (U, n) => '{' + [...Array(n).keys()].filter(p => (U >> p) & 1).join('') + '}';
const fmtPoset = (below, n) => {
  const rel = [];
  for (let p = 0; p < n; p++) for (let q = 0; q < n; q++) if (q !== p && ((below[p] >> q) & 1)) {
    // cover?
    let cover = true;
    for (let r = 0; r < n; r++) if (r !== p && r !== q && ((below[p] >> r) & 1) && ((below[r] >> q) & 1)) cover = false;
    if (cover) rel.push(`${q}<${p}`);
  }
  return rel.length ? rel.join(' ') : '(antichain)';
};

