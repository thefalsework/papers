"""WolframTones classification experiment: can cellular-automaton order alone
manufacture a detectable tonal kernel, or must a kernel be imposed?

WHY THIS EXPERIMENT (and not the obvious one)
---------------------------------------------
The four-position partition (Infrastructure / Distribution / Exploitation /
Refusal) classifies elements *relative to a kernel* `a`.  The tempting test --
"impose a scale on the CA output, then classify the result" -- is CIRCULAR: it
builds the answer (a kernel is present) into the setup, so it can never return a
surprise.  By the project's own anchoring discipline, a check that cannot
surprise is not a check.

The non-circular question is about kernel *detection*, not kernel imposition:

    Does the ORDER that a cellular automaton produces (Wolfram's whole claim --
    CA output is structured, not random) already read as having a tonal center,
    WITHOUT a scale being imposed?

If yes, then the lens's claim that raw CA output is "pre-kernel ordered noise"
that correctly fails to classify is too clean: order alone can fake a kernel.
If no -- if CA-chromatic output is no more centered than random noise, and only
the imposed scale creates a detectable center -- that is positive (surprise-
capable) evidence that the partition tracks genuine kernel-presence.

WolframTones actually generates music from cellular automata mapped onto scales.
This script reconstructs that core mechanism (elementary CA -> scale mapping ->
pitch classes); it is a faithful reconstruction of the method, not a scrape of
the web service.

THREE CONDITIONS (same analysis pipeline)
-----------------------------------------
  (1) random-chromatic : i.i.d. random pitches over all 12 pcs  (noise floor)
  (2) ca-chromatic     : elementary-CA pitches over all 12 pcs  (ordered, no kernel)
  (3) ca-diatonic      : elementary-CA pitches constrained to a major scale (kernel imposed)

Framework prediction: clarity(1) ~= clarity(2) << clarity(3).
Refuting outcome:      clarity(2) >> clarity(1)  (order manufactures a center).

KERNEL DETECTION: Krumhansl-Schmuckler key-finding -- correlate the pitch-class
distribution with the 24 major/minor key profiles.  "Key clarity" = the best
correlation; "concentration" = best minus second-best (how decisively one center
wins).  This is independent of the four-position classification, so using it to
test the lens is not circular.

A SECOND, SMALLER RESULT (the whole-field -> lattice-cell map is degenerate)
---------------------------------------------------------------------------
We also compute the naive map "note-field -> element of Div12" (the subgroup of
Z/12 generated by the field's pitch classes) and locate it in the four cells.
This collapses to the top element for essentially every rich field, which is a
concrete demonstration that classifying a WHOLE note-field in the lattice's cells
is not well defined without further modeling -- empirical support for keeping
that layer [A].

Pure standard library; no dependencies.  Reproducible (fixed seeds).
"""

from __future__ import annotations
import math
import random
from collections import Counter

# ----------------------------------------------------------------------------
# 1. Elementary cellular automaton (the WolframTones engine core)
# ----------------------------------------------------------------------------

def elementary_ca(rule: int, width: int, steps: int, seed: int) -> list[list[int]]:
    """Evolve a width-`width` elementary CA for `steps` rows from a random row.

    Returns a list of rows, each a list of 0/1 cells.  Periodic boundary.
    """
    rng = random.Random(seed)
    row = [rng.randint(0, 1) for _ in range(width)]
    grid = [row]
    table = [(rule >> i) & 1 for i in range(8)]  # table[neighbourhood] = next
    for _ in range(steps - 1):
        nxt = []
        for x in range(width):
            left = row[(x - 1) % width]
            mid = row[x]
            right = row[(x + 1) % width]
            nxt.append(table[(left << 2) | (mid << 1) | right])
        row = nxt
        grid.append(row)
    return grid


# ----------------------------------------------------------------------------
# 2. Map a CA evolution to a pitch-class distribution
# ----------------------------------------------------------------------------

MAJOR_SCALE = [0, 2, 4, 5, 7, 9, 11]  # semitone offsets of a major scale


def ca_to_pc_counts(grid: list[list[int]], mode: str, tonic: int) -> Counter:
    """Map CA `grid` to a pitch-class histogram.

    mode='chromatic': a 12-cell strip selects chromatic pitch classes directly.
    mode='diatonic' : a 7-cell strip selects major-scale degrees rooted at tonic.

    A cell that is ON contributes its pitch class for that row (a note sounds).
    """
    counts: Counter = Counter()
    if mode == "chromatic":
        strip = 12
        for row in grid:
            for i in range(strip):
                if row[i % len(row)]:
                    counts[(tonic + i) % 12] += 1
    elif mode == "diatonic":
        strip = 7
        for row in grid:
            for i in range(strip):
                if row[i % len(row)]:
                    counts[(tonic + MAJOR_SCALE[i]) % 12] += 1
    else:
        raise ValueError(mode)
    return counts


def random_chromatic_pc_counts(n_notes: int, seed: int) -> Counter:
    rng = random.Random(seed)
    counts: Counter = Counter()
    for _ in range(n_notes):
        counts[rng.randint(0, 11)] += 1
    return counts


# ----------------------------------------------------------------------------
# 3. Kernel detection: Krumhansl-Schmuckler key-finding
# ----------------------------------------------------------------------------

KS_MAJOR = [6.35, 2.23, 3.48, 2.33, 4.38, 4.09, 2.52, 5.19, 2.39, 3.66, 2.29, 2.88]
KS_MINOR = [6.33, 2.68, 3.52, 5.38, 2.60, 3.53, 2.54, 4.75, 3.98, 2.69, 3.34, 3.17]


def _pearson(x: list[float], y: list[float]) -> float:
    n = len(x)
    mx = sum(x) / n
    my = sum(y) / n
    num = sum((a - mx) * (b - my) for a, b in zip(x, y))
    dx = math.sqrt(sum((a - mx) ** 2 for a in x))
    dy = math.sqrt(sum((b - my) ** 2 for b in y))
    if dx == 0 or dy == 0:
        return 0.0
    return num / (dx * dy)


def key_clarity(counts: Counter) -> tuple[float, float, str]:
    """Return (best_corr, concentration, best_key_name).

    best_corr      : max correlation with any of the 24 key profiles (= clarity)
    concentration  : best_corr - second_best_corr (how decisively one key wins)
    """
    dist = [float(counts.get(pc, 0)) for pc in range(12)]
    if sum(dist) == 0:
        return 0.0, 0.0, "none"
    corrs: list[tuple[float, str]] = []
    names = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
    for root in range(12):
        prof_maj = [KS_MAJOR[(i - root) % 12] for i in range(12)]
        prof_min = [KS_MINOR[(i - root) % 12] for i in range(12)]
        corrs.append((_pearson(dist, prof_maj), f"{names[root]} major"))
        corrs.append((_pearson(dist, prof_min), f"{names[root]} minor"))
    corrs.sort(reverse=True)
    best, best_name = corrs[0]
    second = corrs[1][0]
    return best, best - second, best_name


# ----------------------------------------------------------------------------
# 4. The naive whole-field -> Div12 element map (demonstrating its degeneracy)
# ----------------------------------------------------------------------------

def generated_divisor(counts: Counter) -> int:
    """Subgroup of Z/12 generated by the present pitch classes, as a divisor d.

    Subgroup <d> with d = gcd(all present pitch classes, 12).  d = 1 means the
    whole group (the top element of Div12); d = 6 is the tritone subgroup {0,6}.
    """
    present = [pc for pc in range(12) if counts.get(pc, 0) > 0]
    g = 12
    for pc in present:
        g = math.gcd(g, pc)
    return g  # a divisor of 12


def div12_cell(divisor: int) -> str:
    """Locate a Div12 element (named by its generating divisor) in the four cells.

    Div12 ~= C3 x C2; kernel g = the tritone = subgroup <6> = {0,6}.
    Mapping divisor -> (C3,C2) coordinate and then to a cell relative to g.
    The point of this function is to show the map collapses: rich fields give
    divisor 1 = top = Distribution, regardless of content.
    """
    # subgroup <d> coordinates in C3 x C2 (by order of the subgroup).
    # <1>=whole (top), <2>,<3>,<4>,<6>=tritone, <12>={0} (bottom).
    coord = {1: (2, 1), 2: (1, 1), 3: (2, 0), 4: (0, 1), 6: (1, 0), 12: (0, 0)}
    a, b = coord[divisor]
    g = (1, 0)  # tritone kernel
    # cells relative to g, computed from the C3 x C2 Heyting structure
    le = lambda p, q: p[0] <= q[0] and p[1] <= q[1]
    x = (a, b)
    if x == (0, 0):
        return "trivial (bottom)"
    if le(x, g):
        return "Infrastructure"
    if le(x, (0, 1)):          # <= not-g
        return "Refusal"
    if le(x, (2, 0)) and not le(x, g):  # <= not-not-g, not <= g
        return "Exploitation"
    return "Distribution"      # straddles both poles


# ----------------------------------------------------------------------------
# 5. Run the experiment
# ----------------------------------------------------------------------------

def mean(xs: list[float]) -> float:
    return sum(xs) / len(xs) if xs else 0.0


def stdev(xs: list[float]) -> float:
    if len(xs) < 2:
        return 0.0
    m = mean(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def run() -> None:
    RULES = [30, 90, 110, 150, 184, 250, 54, 60, 62, 102]
    WIDTH = 24
    STEPS = 64
    SEEDS = list(range(20))
    TONIC = 0  # C

    cond_clarity = {"random-chromatic": [], "ca-chromatic": [], "ca-diatonic": []}
    cond_conc = {"random-chromatic": [], "ca-chromatic": [], "ca-diatonic": []}
    divisor_hist = Counter()
    cell_hist = Counter()

    for rule in RULES:
        for seed in SEEDS:
            grid = elementary_ca(rule, WIDTH, STEPS, seed)
            n_notes = sum(sum(r) for r in grid)  # match note count for the noise floor

            c_rand = random_chromatic_pc_counts(n_notes, seed * 7919 + rule)
            c_ca_chrom = ca_to_pc_counts(grid, "chromatic", TONIC)
            c_ca_diat = ca_to_pc_counts(grid, "diatonic", TONIC)

            for name, counts in (
                ("random-chromatic", c_rand),
                ("ca-chromatic", c_ca_chrom),
                ("ca-diatonic", c_ca_diat),
            ):
                clr, conc, _ = key_clarity(counts)
                cond_clarity[name].append(clr)
                cond_conc[name].append(conc)

            # the degenerate whole-field -> lattice map, on the CA-diatonic field
            d = generated_divisor(c_ca_diat)
            divisor_hist[d] += 1
            cell_hist[div12_cell(d)] += 1

    print("=" * 72)
    print("WolframTones classification experiment")
    print(f"rules={RULES}")
    print(f"width={WIDTH} steps={STEPS} seeds={len(SEEDS)} "
          f"trials/condition={len(RULES) * len(SEEDS)}")
    print("=" * 72)
    print()
    print("KERNEL-DETECTION (Krumhansl-Schmuckler key clarity; higher = more")
    print("decisively tonal). The question: does CA order alone (ca-chromatic)")
    print("read as more centered than random noise?")
    print()
    print(f"  {'condition':<20}{'clarity mean':>14}{'sd':>8}"
          f"{'concentration':>16}{'sd':>8}")
    for name in ("random-chromatic", "ca-chromatic", "ca-diatonic"):
        clr = cond_clarity[name]
        cnc = cond_conc[name]
        print(f"  {name:<20}{mean(clr):>14.3f}{stdev(clr):>8.3f}"
              f"{mean(cnc):>16.3f}{stdev(cnc):>8.3f}")
    print()

    rc = mean(cond_clarity["random-chromatic"])
    cc = mean(cond_clarity["ca-chromatic"])
    cd = mean(cond_clarity["ca-diatonic"])
    gap_order = cc - rc
    gap_kernel = cd - cc
    print(f"  order effect  (ca-chromatic - random-chromatic) = {gap_order:+.3f}")
    print(f"  kernel effect (ca-diatonic  - ca-chromatic)     = {gap_kernel:+.3f}")
    print()
    print("  Reading:")
    if gap_kernel > 0.15 and abs(gap_order) <= 0.10:
        print("  -> Imposing the scale creates the center; CA order alone does not.")
        print("     Consistent with the lens: raw CA output is pre-kernel, and the")
        print("     partition tracks genuine kernel-presence rather than mere order.")
    elif gap_order > 0.15:
        print("  -> CA ORDER ALONE manufactures a detectable center (surprise).")
        print("     The 'ordered noise is pre-kernel' story is too clean: structure")
        print("     can fake a kernel. The lens would over-classify ordered noise.")
    else:
        print("  -> Mixed / weak effects; neither prediction cleanly supported.")
    print()
    print("-" * 72)
    print("WHOLE-FIELD -> Div12 ELEMENT MAP (naive: subgroup generated by the")
    print("field's pitch classes). Demonstrates the map is degenerate.")
    print()
    print(f"  generated-divisor histogram over CA-diatonic fields: {dict(divisor_hist)}")
    print(f"  resulting four-cell histogram:                       {dict(cell_hist)}")
    print()
    top_frac = cell_hist.get("Distribution", 0) / sum(cell_hist.values())
    print(f"  fraction landing in a single cell: {top_frac:.2%}")
    print("  -> A whole note-field collapses to one lattice element (the top),")
    print("     so classifying an ENTIRE field in the cells is not well defined")
    print("     without further modeling. The four-cell reading of a piece stays")
    print("     [A]; only structured pitch-class CONTENT against a fixed kernel is")
    print("     computable. This is the boundary, made concrete.")
    print("=" * 72)


if __name__ == "__main__":
    run()
